function jcLang(){
  try { return localStorage.getItem("jc_lang") || "en"; } catch(e){ return "en"; }
}
function jcT(key){
  var pack = JC_STRINGS[jcLang()] || JC_STRINGS.en;
  return pack[key] != null ? pack[key] : (JC_STRINGS.en[key] != null ? JC_STRINGS.en[key] : key);
}
function jcSetLang(lang){
  try { localStorage.setItem("jc_lang", lang); } catch(e){}
  var pack = JC_STRINGS[lang] || JC_STRINGS.en;
  document.documentElement.setAttribute("dir", pack.dir);
  document.documentElement.setAttribute("lang", pack.lang);
  /* the language button is labelled in the OTHER language: say so, or screen readers mispronounce it (P6) */
  var b = document.getElementById("langBtn");
  if (b) b.setAttribute("lang", pack.lang === "ar" ? "en" : "ar");
}

/* jcFmt("home_villa", {n: "12"}) → "Villa 12". Values are inserted as-is: callers
   still esc() the RESULT before putting it in HTML. */
function jcFmt(key, vals){
  return String(jcT(key)).replace(/\{(\w+)\}/g, function(m, k){
    return vals && vals[k] != null ? String(vals[k]) : m;
  });
}
